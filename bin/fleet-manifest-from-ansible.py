#!/usr/bin/env python3
"""fleet-manifest-from-ansible — derive the nexus fleet manifest from the
ansible inventory on osmium (single declared source, operator ruling
2026-09-19, R1 095905ac).

Truth model
-----------
- **osmium:~/devops/ansible/inventory.yml** — the operator's declared source
  for fleet MEMBERSHIP + ADDRESSES (hostnames, IPs, ansible groups). Never
  edited by this tool; the helium-IP incident proved hand-maintained twins
  diverge, so the nexus manifest is GENERATED from it instead.
- **osmium:~/devops/ansible/fleet-state.yml** — DBA-owned sidecar in the
  same declared directory. Carries the nexus-fleet facts the ansible
  inventory must not express: per-host power/status, and extra nexus-fleet
  members that must NOT become ansible playbook targets (osmium itself is
  the control node; entropy is an unaddressed reserve node).
- **bin/config/fleet-annotations.json** (nexus repo) — nexus judgment layered
  on top: descriptions, environments, per-host services, declared service
  archetypes. Not fleet fact — nexus interpretation; lives in the repo.
- **bin/config/fleet-manifest.json** — the GENERATED artifact consumed by
  fleet-registry-sync.py. Marked generated in `_generated`; regenerated by
  this tool, never hand-edited (drift between regeneration and the committed
  file is what --check reports).

Join semantics: inventory hosts are the membership spine. Sidecar entries
add non-ansible members; sidecar status overrides the default; annotations
enrich. Hosts removed from the ansible inventory are retired via the
monotonic retire rule: a host in the previous manifest's retire list stays
there; a host removed from inventory (and sidecar) is appended —
decommissioning means removing the machine from the declared source, and
the next conversion retires it.

Usage:
  python3 bin/fleet-manifest-from-ansible.py                 # ssh osmium, print
  python3 bin/fleet-manifest-from-ansible.py --write         # ... and write manifest
  python3 bin/fleet-manifest-from-ansible.py --dir ~/ansible # local dir mode (tests)
  python3 bin/fleet-manifest-from-ansible.py --check         # diff vs committed
Env: OSMIUM_ANSSH (default codex@192.168.1.162), OSMIUM_ANSIBLE_DIR
(default /home/codex/devops/ansible).
"""

import argparse
import json
import os
import re
import subprocess
import sys
import uuid

import yaml

SELF_DIR = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(SELF_DIR, ".."))
MANIFEST_PATH = os.path.join(REPO, "bin", "config", "fleet-manifest.json")
ANNOTATIONS_PATH = os.path.join(REPO, "bin", "config", "fleet-annotations.json")

OSMIUM_SSH = os.environ.get("OSMIUM_ANSSH", "codex@192.168.1.162")
OSMIUM_DIR = os.environ.get("OSMIUM_ANSIBLE_DIR", "/home/codex/devops/ansible")

DEFAULT_STATUS = "OFFLINE"
RETIRED_STATUS = "RETIRED"

GENERATED_HEADER = (
    "GENERATED by bin/fleet-manifest-from-ansible.py from the ansible "
    "inventory on osmium (single declared source, operator ruling "
    "2026-09-19). Do not hand-edit: membership/addresses come from "
    "~/devops/ansible/inventory.yml, power state from fleet-state.yml "
    "alongside it, nexus judgment from fleet-annotations.json in the repo. "
    "Regenerate with --write; --check reports drift.")


def read_source_dir(d):
    """Read inventory.yml + fleet-state.yml from a local directory."""
    inv_path = os.path.join(d, "inventory.yml")
    state_path = os.path.join(d, "fleet-state.yml")
    with open(inv_path, encoding="utf-8") as fh:
        inventory = yaml.safe_load(fh) or {}
    state = {}
    if os.path.exists(state_path):
        with open(state_path, encoding="utf-8") as fh:
            state = yaml.safe_load(fh) or {}
    return inventory, state


ANSI_RE = re.compile(
    r"\x1b(?:\[[0-9;?]*[a-zA-Z]|\][^\x07]*?(?:\x07|\x1b\\)|[()][0-9A-B])")


def clean_channel_payload(raw, nonce):
    """Extract the command payload from an ssh exec stream whose remote
    side sprays MOTD/ANSI junk (osmium's pam_motd fastfetch fires for every
    session type, corrupting naive `ssh host cat` captures). The remote
    command is wrapped in echo-nonce delimiters; everything before the
    first nonce and after the last is discarded by construction."""
    first = raw.find(nonce)
    if first < 0:
        return ""                      # delimiters absent -> nothing usable
    last = raw.rfind(nonce)
    payload = raw[first + len(nonce):last] if last > first else ""
    payload = ANSI_RE.sub("", payload).replace("\r\n", "\n").replace("\r", "\n")
    return payload.strip("\n")


def _ssh_payload(cmd):
    """Run a remote command through the nonce-delimited channel; returns
    the clean payload (raise SystemExit on ssh failure)."""
    nonce = f"__FMA_{uuid.uuid4().hex[:16]}__"
    r = subprocess.run(
        ["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=5",
         OSMIUM_SSH, f"echo {nonce}; {cmd}; echo {nonce}"],
        capture_output=True, text=True, timeout=25)
    if r.returncode != 0:
        raise SystemExit(
            f"FATAL: ssh fetch failed from {OSMIUM_SSH}: {r.stderr.strip()}")
    return clean_channel_payload(r.stdout, nonce)


def fetch_source_via_ssh():
    """Fetch both source files over ssh from osmium."""
    outs = []
    for name in ("inventory.yml", "fleet-state.yml"):
        payload = _ssh_payload(
            f"if [ -f {OSMIUM_DIR}/{name} ]; then "
            f"cat {OSMIUM_DIR}/{name}; else exit 3; fi")
        if payload == "":
            if name == "fleet-state.yml":
                outs.append("")          # sidecar optional at bootstrap
                continue
            raise SystemExit(
                f"FATAL: empty payload for {name} from {OSMIUM_SSH}")
        outs.append(payload + "\n")
    inv = yaml.safe_load(outs[0]) or {}
    state = yaml.safe_load(outs[1]) if outs[1].strip() else {}
    return inv, state


def flatten_inventory_hosts(inventory):
    """ansible inventory -> {hostname: {'groups': [...], 'ansible_host': ip}}.
    Walks children recursively; honors ansible_host; skips commented-out
    entries (they never reach yaml) and localhost-style rows."""
    hosts = {}

    def walk(node, groups):
        for key, val in (node or {}).items():
            if not isinstance(val, dict):
                continue
            if key == "hosts":
                for hn, hv in val.items():
                    entry = hosts.setdefault(hn, {"groups": [], "vars": {}})
                    if isinstance(hv, dict):
                        entry["vars"].update(hv)
                    entry["groups"].extend(
                        g for g in groups if g not in entry["groups"])
            elif key == "vars":
                continue
            elif key == "children":
                for gname, gnode in val.items():
                    walk(gnode, groups + [gname])
            else:
                # any other dict is a group node ("all", nested wrappers)
                walk(val, groups)

    walk(inventory, [])
    return hosts


def build_manifest(inventory, state, annotations, previous):
    """Join the three declared layers into the manifest structure."""
    inv_hosts = flatten_inventory_hosts(inventory)
    state_hosts = (state.get("fleet_state") or {}).get("hosts", {}) \
        if isinstance(state, dict) else {}
    extra_members = (state.get("fleet_state") or {}).get("extra_members", []) \
        if isinstance(state, dict) else []
    ann_hosts = {a.get("hostname"): a for a in
                 (annotations or {}).get("hosts", [])}
    ann_services = (annotations or {}).get("services", [])
    ann_defaults = (annotations or {}).get("defaults", {})

    # membership spine: ansible hosts first, then sidecar extra members
    members = list(inv_hosts.keys())
    for hn in extra_members:
        if hn not in members:
            members.append(hn)

    prev_retire = set((previous or {}).get("retire", {}).get("hostnames", []))
    prev_members = {h.get("hostname") for h in (previous or {}).get("fleet", [])}
    retire = set(prev_retire)

    fleet = []
    for hn in members:
        inv = inv_hosts.get(hn, {})
        st = state_hosts.get(hn, {})
        ann = ann_hosts.get(hn, {})

        # status: sidecar is authority, else annotation default, else OFFLINE
        status = st.get("status") or ann.get("status") \
            or ann_defaults.get("status", DEFAULT_STATUS)

        # address: ansible_host from inventory is the declared source;
        # sidecar/annotations may NOT fabricate one for an ansible host
        ip = inv.get("vars", {}).get("ansible_host") or st.get("ip_address") \
            or ann.get("ip_address")
        if hn in inv_hosts and not ip:
            raise ValueError(f"ansible host {hn!r} has no ansible_host address")

        host = {
            "hostname": hn,
            "description": ann.get("description",
                                   st.get("description",
                                          f"declared via ansible inventory ({', '.join(inv.get('groups', [])) or 'no group'})")),
            "status": status,
        }
        if ip:
            host["ip_address"] = ip
        if ann.get("environment"):
            host["environment"] = ann["environment"]
        if "services" in ann:
            host["services"] = ann["services"]
        if ann.get("os"):
            host["os"] = ann["os"]
        if ann.get("server_type"):
            host["server_type"] = ann["server_type"]
        fleet.append(host)

    fleet.sort(key=lambda h: h["hostname"])  # deterministic output

    # monotonic retire: previous retire ∪ (previous members now absent),
    # MINUS current members — declared membership always wins so the
    # generated manifest can never carry a declare+retire contradiction
    # (fleet-registry-sync refuses exactly that).
    for hn in prev_members:
        if hn and hn not in members:
            retire.add(hn)
    retire -= set(members)

    manifest = {
        "_generated": GENERATED_HEADER,
        "services": ann_services,
        "fleet": fleet,
        "retire": {
            "_comment": "Derived: hosts removed from the declared source "
                        "(osmium ansible dir) are retired here on the next "
                        "conversion. Never deleted from the registry — "
                        "provenance kept.",
            "hostnames": sorted(retire),
        },
    }
    return manifest


def load_json(path):
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def deep_diff(a, b, path=""):
    """Yield (path, old, new) for differences between two JSON-ish trees."""
    if isinstance(a, dict) and isinstance(b, dict):
        for k in sorted(set(a) | set(b)):
            yield from deep_diff(a.get(k), b.get(k), f"{path}.{k}" if path else k)
    elif isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            yield (path, f"len={len(a)}", f"len={len(b)}")
        else:
            for i, (x, y) in enumerate(zip(a, b)):
                yield from deep_diff(x, y, f"{path}[{i}]")
    elif a != b:
        yield (path, a, b)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dir", help="local source dir (default: ssh osmium)")
    ap.add_argument("--write", action="store_true",
                    help="write the generated manifest to bin/config/")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if regeneration differs from committed manifest")
    ap.add_argument("--out", help="write to this path instead of the default")
    args = ap.parse_args()

    if args.dir:
        inventory, state = read_source_dir(args.dir)
    else:
        inventory, state = fetch_source_via_ssh()

    annotations = load_json(ANNOTATIONS_PATH) or {}
    previous = load_json(MANIFEST_PATH)
    manifest = build_manifest(inventory, state, annotations, previous)

    rendered = json.dumps(manifest, indent=2, ensure_ascii=False,
                          sort_keys=False) + "\n"

    target = args.out or MANIFEST_PATH
    committed = None
    if os.path.exists(target) and not args.out:
        with open(target, encoding="utf-8") as fh:
            committed = fh.read()

    if args.check:
        # compare semantic content, ignoring generated/comment headers
        def strip_headers(node):
            if isinstance(node, dict):
                return {k: strip_headers(v) for k, v in node.items()
                        if k not in ("_generated", "_comment")}
            if isinstance(node, list):
                return [strip_headers(x) for x in node]
            return node

        a = strip_headers(json.loads(rendered))
        if committed:
            b = strip_headers(json.loads(committed))
            # compare per-host (keyed), not positional: fleet order is
            # meaningless, and a positional diff misreads re-sorting as drift
            def by_host(m):
                return {h["hostname"]: h for h in m.get("fleet", [])}
            diffs = []
            bh, ah = by_host(b), by_host(a)
            for hn in sorted(set(bh) | set(ah)):
                if hn not in ah:
                    diffs.append((f"fleet.{hn}", "present", "REMOVED"))
                elif hn not in bh:
                    diffs.append((f"fleet.{hn}", None, "ADDED"))
                else:
                    diffs += [(f"fleet.{hn}.{p}", o, n)
                              for p, o, n in deep_diff(bh[hn], ah[hn])]
            # retire list compared positionally (sorted by construction)
            rb = sorted(b.get("retire", {}).get("hostnames", []))
            ra = sorted(a.get("retire", {}).get("hostnames", []))
            if rb != ra:
                diffs.append(("retire.hostnames", rb, ra))
            # declared service archetypes compared keyed by name
            sb = {s["name"]: s for s in b.get("services", [])}
            sa = {s["name"]: s for s in a.get("services", [])}
            for sn in sorted(set(sb) | set(sa)):
                if sb.get(sn) != sa.get(sn):
                    diffs.append((f"services.{sn}", sb.get(sn), sa.get(sn)))
            if diffs:
                print(f"DRIFT: {len(diffs)} difference(s) between committed "
                      "manifest and regeneration from osmium:")
                for p, old, new in diffs[:20]:
                    print(f"  {p}: {old!r} -> {new!r}")
                return 1
            print("in sync: committed manifest equals regeneration from "
                  "the declared source")
            return 0
        print("no committed manifest to compare")
        return 1

    if args.write:
        with open(target, "w", encoding="utf-8") as fh:
            fh.write(rendered)
        n = len(manifest["fleet"])
        print(f"wrote {target} ({n} hosts, "
              f"retire={manifest['retire']['hostnames']})")
        return 0

    print(rendered, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
