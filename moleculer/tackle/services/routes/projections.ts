// ── Helpers ───────────────────────────────────────────────────────────

const GENERATED_HEADER = (name: string) =>
  `<!-- GENERATED by tackle-projector; source: projection:${name}; do not edit -->\n`;

/**
 * Deterministic {{var}} template substitution.
 * Replaces all {{varname}} tokens with values from the context object.
 */
function renderTemplate(template: string, ctx: Record<string, string>): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_match, name) => {
    return ctx[name] !== undefined ? ctx[name] : `{{${name}}}`;
  });
}

/**
 * Build context for a single projection row from source_query results + persona/procedures.
 */
async function buildContext(
  projection: any,
  queryRow: Record<string, any>
): Promise<Record<string, string>> {
  const ctx: Record<string, string> = {};

  // Merge query row values
  for (const [k, v] of Object.entries(queryRow)) {
    if (v !== null && v !== undefined) {
      ctx[k] = String(v);
    }
  }

  // Resolve persona if this projection needs it and has a role column
  const role = queryRow.role || queryRow.name;
  if (role && projection.template.includes("{{persona_body}}")) {
    const persona = await getPersonaForRole(role);
    ctx.persona_body = persona || `Activate as: ${role}.\n\nYou are the ${role}. Respond to user requests directly.`;
  }

  // Resolve procedures list if needed
  if (role && projection.template.includes("{{procedures_list}}")) {
    const procs = await getProceduresForRole(role);
    ctx.procedures_list = procs || "(no procedures available)";
  }

  return ctx;
}

/**
 * Compute SHA-256 of a string.
 */
function sha256(content: string): string {
  return createHash("sha256").update(content).digest("hex");
}

/**
 * Write a file with drift protection (.bak on overwrite).
 * Returns { written: boolean, sha: string, backedUp: boolean }
 */
function writeFileWithDrift(
  targetPath: string,
  content: string,
  lastSha256: string | null
): { written: boolean; sha: string; backedUp: boolean } {
  const newSha = sha256(content);
  const dir = path.dirname(targetPath);

  // Ensure directory exists
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
  }

  if (existsSync(targetPath)) {
    const existingContent = readFileSync(targetPath, "utf8");
    const existingSha = sha256(existingContent);

    // Idempotency: if unchanged, skip
    if (existingSha === newSha) {
      return { written: false, sha: newSha, backedUp: false };
    }

    // Drift protection: if known sha differs, create .bak
    if (lastSha256 && lastSha256 !== existingSha) {
      const ts = new Date().toISOString().replace(/[:.]/g, "-");
      const bakPath = `${targetPath}.bak-${ts}`;
      renameSync(targetPath, bakPath);
      writeFileSync(targetPath, content, "utf8");
      return { written: true, sha: newSha, backedUp: true };
    }

    // Untracked target: we have no stored sha, so we cannot prove the
    // existing file is ours. Never silently overwrite hand-authored
    // content — back it up first, then adopt.
    if (!lastSha256) {
      const ts = new Date().toISOString().replace(/[:.]/g, "-");
      const bakPath = `${targetPath}.bak-${ts}`;
      renameSync(targetPath, bakPath);
      writeFileSync(targetPath, content, "utf8");
      return { written: true, sha: newSha, backedUp: true };
    }

    // No drift (sha matches) — overwrite
    writeFileSync(targetPath, content, "utf8");
    return { written: true, sha: newSha, backedUp: false };
  }

  // New file
  writeFileSync(targetPath, content, "utf8");
  return { written: true, sha: newSha, backedUp: false };
}

