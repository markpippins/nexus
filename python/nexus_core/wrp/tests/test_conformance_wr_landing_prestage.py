    # ---- 9. never-drop guard -------------------------------------------------

    def test_ac14_never_drop_guard(self):
        self._refused("DROP TABLE vision.work_request_shape_registry", "P1022")
        self._refused("DROP TABLE conduit.work_request_events", "P1022")
        # non-pinned tables drop freely
        self._sql("CREATE TABLE vision.tmp_not_pinned (id int)")
        self._sql("DROP TABLE vision.tmp_not_pinned")
        # hatched drop admitted (session-LOCAL: SET + DROP on one connection).
        # A pinned object must NOT be dropped even hatched in this proof —
        # instead prove the hatch releases the guard for a sacrificial pinned-
        # SCHEMA table, then verify pinned objects survived the whole test.
        self._sql("CREATE TABLE vision.tmp_hatched (id int)")
        self._sql_hatched("DROP TABLE vision.tmp_hatched",
                          setting='vision.allow_wr_object_drop')
        # pinned tables still present
        rows = self._sql("""
            SELECT count(*) FROM information_schema.tables
            WHERE table_schema='vision' AND table_name='work_request_shape_registry'
        """)
        self.assertEqual(rows[0][0], 1)


