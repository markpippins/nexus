    # ---- 6. C4 business_key uniqueness --------------------------------------

    def test_ac11_duplicate_business_key_refused_nulls_coexist(self):
        self._ratify_shape("v0.1")
        try:
            self._sql(self._canonical_row(wr_id="wr-u1", business_key="bk-dup"))
            import psycopg2
            try:
                self._sql(self._canonical_row(wr_id="wr-u2", business_key="bk-dup"))
                self.fail("duplicate business_key must violate the unique index")
            except psycopg2.Error as e:
                self.assertIn("uq_vision_work_requests_business_key", str(e))
        finally:
            self._unratify_shape("v0.1")
        # NULL (legacy) keys never collide: add another hatched legacy row.
        # (Self-contained: counts only skeleton rows + this test's row — test
        # methods run alphabetically, so cross-test row assumptions are unsafe.)
        self._sql_hatched(
            "INSERT INTO vision.work_requests (wr_id, status) VALUES ('legacy-5','open')")
        rows = self._sql("""
            SELECT count(*) FROM vision.work_requests
            WHERE wr_id IN ('legacy-1','legacy-2','legacy-5')
              AND business_key IS NULL
        """)
        self.assertEqual(rows[0][0], 3,
                         "all NULL-key legacy rows coexist (NULLs exempt from unique)")

    # ---- 7. C5 field/type conformance ---------------------------------------

    def test_ac12_conformance_refusals(self):
        self._ratify_shape("v0.1")
        try:
            cases = [
                ({"relation_payload": None}, "relation_payload"),
                ({"relation_payload": json.dumps([1, 2])}, "relation_payload must be a JSON object"),
                ({"business_key": None}, "business_key"),
                ({"business_key": ""}, "business_key"),
                ({"intent_payload": None}, "intent_payload"),
                ({"intent_payload": json.dumps("nope")}, "intent_payload must be a JSON object"),
                ({"intent_payload": json.dumps({"desired_outcome": "ok"})}, "problem_statement"),
                ({"intent_payload": json.dumps({"problem_statement": "p", "desired_outcome": ""})}, "desired_outcome"),
                ({"intent_payload": json.dumps({"problem_statement": "p", "desired_outcome": "d", "priority": "urgent"})}, "priority"),
                ({"intent_payload": json.dumps({"problem_statement": "p", "desired_outcome": "d", "rogue": 1})}, "outside WP1 v0.1 envelope"),
                ({"lineage": json.dumps({"rogue": 1})}, "lineage"),
                ({"decomposition": json.dumps({"steps": "not-an-array"})}, "steps"),
                ({"evidence_obligations": json.dumps({"nope": True})}, "evidence_obligations must be an array"),
                ({"inquiry": json.dumps({"read_set_scope": {}, "evaluator_ref": "e",
                                         "expected_outcome_type": "t",
                                         "evidence_requirements": [],
                                         "fifth": 1})}, "fifth field"),
                ({"inquiry": json.dumps({"read_set_scope": [], "evaluator_ref": "e",
                                         "expected_outcome_type": "t",
                                         "evidence_requirements": []})}, "read_set_scope must be an object"),
            ]
            for i, (overrides, fragment) in enumerate(cases):
                merged = {"wr_id": f"wr-c5-{i}", "business_key": f"bk-c5-{i}"}
                merged.update(overrides)
                self._refused(
                    self._canonical_row(**merged),
                    fragment)
        finally:
            self._unratify_shape("v0.1")

