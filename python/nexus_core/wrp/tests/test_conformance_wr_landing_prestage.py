def _admin_connect(dbname):
    import psycopg2
    # Connect to the maintenance database to create/drop throwaway DBs.
    dsn = DSN.rsplit("/", 1)[0] + "/" + dbname
    return psycopg2.connect(dsn)


def _exec(cur, sql):
    cur.execute(sql)


class _HermeticDB:
    """Throwaway per-run database with the V163 pre-stage applied."""

    def __init__(self):
        self.dbname = f"nexus_v163_test_{os.getpid()}"

    def __enter__(self):
        conn = _admin_connect("postgres")
        conn.autocommit = True
        with conn.cursor() as cur:
            cur.execute(f'DROP DATABASE IF EXISTS "{self.dbname}"')
            cur.execute(f'CREATE DATABASE "{self.dbname}"')
        conn.close()
        self.conn = _admin_connect(self.dbname)
        self.conn.autocommit = True
        self._build_skeleton()
        self._apply_v163()
        return self

    def __exit__(self, *exc):
        try:
            self.conn.close()
        finally:
            conn = _admin_connect("postgres")
            conn.autocommit = True
            with conn.cursor() as cur:
                cur.execute(f'DROP DATABASE IF EXISTS "{self.dbname}" WITH (FORCE)')
            conn.close()

    def _build_skeleton(self):
        """Faithful baseline of the touched surfaces (V163 §7 evidence)."""
        with self.conn.cursor() as cur:
            for schema in ("vision", "semantics", "conduit"):
                cur.execute(f"CREATE SCHEMA IF NOT EXISTS {schema}")
            # semantics.canonical_asset — FK target for work_requests.asset_id
            cur.execute("""
                CREATE TABLE semantics.canonical_asset (
                    asset_id uuid PRIMARY KEY DEFAULT gen_random_uuid()
                )
            """)
            # vision.work_requests — 13-column pre-V163 baseline (verified live)
            cur.execute("""
                CREATE TABLE vision.work_requests (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    wr_id text,
                    dco_json text,
                    context jsonb,
                    status text,
                    step_outputs text,
                    recorded_on_dt timestamptz NOT NULL DEFAULT now(),
                    recorded_until_dt timestamptz NOT NULL DEFAULT 'infinity'::timestamptz,
                    work_request_uuid text,
                    title text,
                    nexus_work_request_id uuid,
                    asset_id uuid REFERENCES semantics.canonical_asset(asset_id),
                    entity_key text
                )
            """)
            # Two legacy rows (as live: business_key will be NULL after §2).
            cur.execute("""
                INSERT INTO vision.work_requests (wr_id, status)
                VALUES ('legacy-1', 'archived'), ('legacy-2', 'archived')
            """)
            # conduit WR runtime tables (never-drop pins reference them)
            cur.execute("""
                CREATE TABLE conduit.work_request_events (
                    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    work_request_id uuid,
                    event_type text,
                    payload jsonb,
                    created_at timestamptz NOT NULL DEFAULT now()
                )
            """)
            cur.execute("""
                CREATE TABLE conduit.work_request_state (
                    work_request_id uuid PRIMARY KEY,
                    state text,
                    updated_at timestamptz NOT NULL DEFAULT now()
                )
            """)

    def _apply_v163(self):
        with self.conn.cursor() as cur:
            with open(V163_PATH, "r", encoding="utf-8") as fh:
                sql = fh.read()
            # Strip the trailing §7 comment block safely: psql runs the whole
            # file fine (comments are legal SQL), so no stripping is needed.
            cur.execute(sql)


class TestWRLandingPrestage(unittest.TestCase):
    """V163 conformance — C1..C5 + hatch + never-drop guard."""

    @classmethod
    def setUpClass(cls):
        cls.herm = _HermeticDB().__enter__()
        cls.conn = cls.herm.conn

    @classmethod
    def tearDownClass(cls):
        cls.herm.__exit__()

    # ---- helpers ----------------------------------------------------------

    def _sql(self, query, params=None):
        """Run a statement on a FRESH connection; return rows.

        Fresh connection per statement: a refused statement aborts its
        transaction, and we don't want that poisoning the next case.
        """
        import psycopg2
        conn = _admin_connect(self.herm.dbname)
        try:
            cur = conn.cursor()
            cur.execute(query, params)
            rows = cur.fetchall() if cur.description else []
            conn.commit()
            return rows
        except psycopg2.Error:
            conn.rollback()
            raise
        finally:
            conn.close()

    def _refused(self, query, expect_fragment=None):
        """Assert the statement raises, and (optionally) the message fragment."""
        import psycopg2
        try:
            self._sql(query)
        except psycopg2.Error as e:
            msg = (e.diag.message_primary or "") if e.diag else str(e)
            if expect_fragment:
                self.assertIn(expect_fragment, msg)
            return msg
        self.fail(f"expected refusal, statement succeeded: {query[:120]}")

    def _set_hatch(self, on):
        # NOTE: the hatch is session-LOCAL — this helper is only meaningful on
        # the same connection that later runs the hatched statement. Use
        # _sql_hatched for that; this helper exists for explicit "hatch off"
        # assertions only.
        self._sql(f"SET vision.allow_ungated_wr_landing = {'on' if on else 'off'}")

    def _sql_hatched(self, query, setting='vision.allow_ungated_wr_landing', value='on'):
        """Run SET <setting>=<value> + query on ONE connection.

        The hatch is session-LOCAL by design (the security property under
        test): a SET on connection A never leaks to connection B. Hatched
        scenarios must therefore issue the SET and the statement on the same
        connection, then close it — after which the hatch is verifiably gone.
        """
        import psycopg2
        conn = _admin_connect(self.herm.dbname)
        try:
            cur = conn.cursor()
            cur.execute(f"SET {setting} = '{value}'")
            cur.execute(query)
            rows = cur.fetchall() if cur.description else []
            conn.commit()
            return rows
        except psycopg2.Error:
            conn.rollback()
            raise
        finally:
            conn.close()

    def _ratify_shape(self, version="v0.1"):
        self._sql(f"""
            INSERT INTO vision.work_request_shape_registry
                (shape_version, artifact_path, artifact_sha256, ratification_state)
            VALUES ('{version}', 'schemas/work-request/canonical-shape.{version}.json',
                    '{'a' * 64}', 'ratified')
        """)

    def _unratify_shape(self, version="v0.1"):
        # DELETE (not UPDATE-to-superseded): shape_version is the PRIMARY KEY,
        # so a superseded row would collide with the next test's re-ratify.
        # The guard ignores DELETEs (tombstones are contract-legal), so this
        # is the clean per-test teardown.
        self._sql(f"DELETE FROM vision.work_request_shape_registry WHERE shape_version = '{version}'")

    def _canonical_row(self, **overrides):
        """A fully conforming v0.1 canonical payload (per the artifact)."""
        row = {
            "wr_id": "wr-canonical-1",
            "status": "open",
            "business_key": "bk-1",
            "relation_payload": json.dumps({"source": "rover", "ref": "x1"}),
            "intent_payload": json.dumps({
                "problem_statement": "something is broken",
                "desired_outcome": "it works again",
                "priority": "high",
            }),
            "lineage": json.dumps({"plan": "plan-0003"}),
            "decomposition": json.dumps({"steps": [{"n": 1, "do": "a"}]}),
            "execution_linkage": json.dumps({
                "lease_ref": "lease-1",
                "attempt_refs": ["att-1"],
                "receipt_refs": ["rec-1"],
            }),
            "evidence_obligations": json.dumps([{"kind": "log"}]),
            "inquiry": json.dumps({
                "read_set_scope": {"tables": ["nebula.agent_records"]},
                "evaluator_ref": "eval-1",
                "expected_outcome_type": "report",
                "evidence_requirements": ["ev-1"],
            }),
            "shape_version": "v0.1",
        }
        row.update(overrides)
        cols = ", ".join(row.keys())
        vals = []
        for v in row.values():
            if v is None:
                vals.append("NULL")
            elif isinstance(v, bool) or isinstance(v, int):
                vals.append(str(v))
            else:
                vals.append("'" + str(v).replace("'", "''") + "'")
        return f"INSERT INTO vision.work_requests ({cols}) VALUES ({', '.join(vals)})"

    # ---- 1. apply + postconditions -----------------------------------------

    def test_ac1_apply_postconditions(self):
        rows = self._sql("""
            SELECT column_name FROM information_schema.columns
            WHERE table_schema='vision' AND table_name='work_requests'
              AND column_name IN ('business_key','relation_payload','intent_payload',
                                  'lineage','decomposition','execution_linkage',
                                  'evidence_obligations','inquiry','shape_version')
        """)
        self.assertEqual(len(rows), 9)
        idx = self._sql("""
            SELECT indexdef FROM pg_indexes
            WHERE schemaname='vision' AND tablename='work_requests'
              AND indexname='uq_vision_work_requests_business_key'
        """)
        self.assertEqual(len(idx), 1)
        self.assertIn("UNIQUE", idx[0][0])
        reg = self._sql("SELECT count(*) FROM vision.work_request_shape_registry")
        self.assertEqual(reg[0][0], 0, "registry must ship EMPTY (no seeding)")

    # ---- 2. legacy admission + C2 hatch-first -------------------------------

    def test_ac2_legacy_write_passes_pre_ratification_no_hatch(self):
        # C2 correction of the old strict-gate: legacy-shaped writes are not
        # stranded pre-ratification (no P1021 for legacy rows).
        self._sql("""
            INSERT INTO vision.work_requests (wr_id, status) VALUES ('legacy-3', 'open')
        """)
        rows = self._sql("SELECT count(*) FROM vision.work_requests WHERE wr_id='legacy-3'")
        self.assertEqual(rows[0][0], 1)

    def test_ac3_hatched_legacy_write_passes_and_hatch_is_session_local(self):
        self._sql_hatched(
            "INSERT INTO vision.work_requests (wr_id, status) VALUES ('legacy-4', 'open')")
        rows = self._sql("SELECT count(*) FROM vision.work_requests WHERE wr_id='legacy-4'")
        self.assertEqual(rows[0][0], 1)
        # hatch must be gone on a fresh connection (session-LOCAL)
        self._refused(self._canonical_row(wr_id="wr-hatch-leak", business_key="bk-leak"),
                      "P1021")

    # ---- 3. canonical gate pre/post ratification ----------------------------

    def test_ac4_canonical_write_pre_ratification_refused_p1021(self):
        self._refused(self._canonical_row(business_key="bk-prerat"),
                      "P1021: no ratified canonical WorkRequest shape")

    def test_ac5_hatch_first_admits_canonical_write_pre_ratification(self):
        # C2: the hatch is evaluated BEFORE the P1021 refusal — the same
        # canonical write that is refused unhatched (AC4) passes hatched,
        # even with NO ratified shape registered.
        self._sql_hatched(self._canonical_row(
            wr_id="wr-hatched-pre", business_key="bk-hatched"))
        rows = self._sql("SELECT count(*) FROM vision.work_requests WHERE wr_id='wr-hatched-pre'")
        self.assertEqual(rows[0][0], 1)

